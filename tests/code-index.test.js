// ─── Session compactor ─────────────────────────────────────────────

describe('session compactor', () => {
  let db;
  const project = path.join(os.tmpdir(), 'ac-compact-' + Date.now());
  beforeEach(() => { db = createTestDb(); });
  afterEach(() => { db.close(); });

  it('compacts a raw transcript with template fallback when no LLM', async () => {
    const entries = [];
    for (let i = 0; i < 50; i++) {
      entries.push({ role: 'user', content: 'step ' + i + ': refactor the auth module' });
      entries.push({ role: 'assistant', content: 'did step ' + i + ' with success' });
    }
    const r = await compactor.compactTranscript(entries, {});
    assert.ok(r.summary.length > 20);
    assert.ok(r.chunks >= 1);
    assert.ok(r.inputChars > 0);
    assert.ok(r.ratio > 0 && r.ratio < 0.5, 'should compress meaningfully');
  });

  it('compacts session observations and stores a history record', async () => {
    const insert = db.prepare(
      "INSERT INTO observations (session_id, project_path, type, title, content, tags) VALUES (?, ?, 'decision', ?, ?, '[]')"
    );
    for (let i = 0; i < 45; i++) {
      insert.run('sess-1', project, 'Decision ' + i, 'Chose approach ' + i + ' for the token budget engine');
    }
    const r = await compactor.compactObservations(db, { sessionId: 'sess-1', project });
    assert.equal(r.inputCount, 45);
    assert.equal(r.stored, true);
    assert.ok(r.summary.length > 20);
    const history = compactor.getCompactionHistory(db, { sessionId: 'sess-1' });
    assert.equal(history.length, 1);
    assert.equal(history[0].output, r.summary);
  });

  it('returns empty for a session with no observations', async () => {
    const r = await compactor.compactObservations(db, { sessionId: 'sess-empty', project });
    assert.equal(r.inputCount, 0);
    assert.equal(r.summary, '');
    assert.equal(r.stored, false);
  });
});

// ─── Diff ingestion (integration: real temp project + generator) ───

describe('code-index diff ingestion', () => {
  let db;
  let project;
  beforeEach(() => {
    db = createTestDb();
    project = fs.mkdtempSync(path.join(os.tmpdir(), 'ac-diff-'));
  });
  afterEach(() => {
    db.close();
    fs.rmSync(project, { recursive: true, force: true });
  });

  it('re-indexes changed files via the deterministic generator', async () => {
    fs.mkdirSync(path.join(project, 'src'), { recursive: true });
    fs.writeFileSync(path.join(project, 'src', 'mod.js'), 'export function hello(name) {\n  return "hi " + name;\n}\n');
    fs.writeFileSync(path.join(project, 'src', 'other.js'), 'export const TWO = 2;\n');

    // Full ingest first
    const r1 = codeIndex.ingestProject(db, project, { regenerate: true });
    assert.equal(r1.status, 'ok');
    const before = db.prepare('SELECT COUNT(*) c FROM code_symbols WHERE project_path = ?').get(project).c;
    assert.ok(before >= 1);

    // Modify one file, then diff-ingest it
    fs.writeFileSync(path.join(project, 'src', 'mod.js'), 'export function hello(name, greet = "yo") {\n  return greet + " " + name;\n}\n');
    const r = await codeIndex.ingestDiff(db, project, { files: ['src/mod.js'] });
    assert.equal(r.status, 'ok');
    assert.deepEqual(r.changedFiles, ['src/mod.js']);
    assert.equal(r.memorySaved, true);
    const row = db.prepare("SELECT * FROM code_symbols WHERE project_path = ? AND symbol_name = 'hello'").get(project);
    assert.ok(row.body.includes('greet'), 'body should reflect the change');
    // A change memory observation was recorded
    const obs = db.prepare("SELECT COUNT(*) c FROM observations WHERE project_path = ? AND tags LIKE '%code-change%'").get(project).c;
    assert.equal(obs, 1);
  });
});
