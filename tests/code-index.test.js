// ─── Ingestion ──────────────────────────────────────────────────────

describe('code-index ingestion', () => {
  let db;
  const project = path.join(os.tmpdir(), 'ac-codeidx-test-' + Date.now());
  beforeEach(() => { db = createTestDb(); });
  afterEach(() => { db.close(); });

  it('ingests symbols from a graph object', () => {
    const r = codeIndex.ingestProject(db, project, { graph: buildGraph() });
    assert.equal(r.status, 'ok');
    assert.equal(r.symbols, 4);
    assert.equal(r.inserted, 4);
    const rows = db.prepare('SELECT * FROM code_symbols WHERE project_path = ?').all(project);
    assert.equal(rows.length, 4);
    const emb = rows.find(x => x.symbol_name === 'computeEmbedding');
    assert.equal(emb.file_path, 'src/core/embedding.js');
    assert.equal(emb.body, '{\n  return vec;\n}');
    assert.equal(emb.body_hash.length, 16);
  });

  it('is idempotent — re-ingest with unchanged bodies updates nothing', () => {
    codeIndex.ingestProject(db, project, { graph: buildGraph() });
    const r2 = codeIndex.ingestProject(db, project, { graph: buildGraph() });
    assert.equal(r2.inserted, 0);
    assert.equal(r2.updated, 0);
  });

  it('updates symbols when a body changes and preserves summaries', () => {
    codeIndex.ingestProject(db, project, { graph: buildGraph() });
    db.prepare('UPDATE code_symbols SET summary = ? WHERE symbol_name = ?').run('summarizes text', 'computeEmbedding');
    const g2 = buildGraph();
    g2.graph['src/core/embedding.js'].symbols[0].body = '{\n  return newVec;\n}';
    const r = codeIndex.ingestProject(db, project, { graph: g2 });
    assert.equal(r.updated, 1);
    const row = db.prepare("SELECT * FROM code_symbols WHERE symbol_name = 'computeEmbedding'").get();
    assert.equal(row.summary, 'summarizes text', 'existing summary must survive re-ingest');
    assert.equal(row.body, '{\n  return newVec;\n}');
  });

  it('drops symbols for files removed from the graph on full ingest', () => {
    codeIndex.ingestProject(db, project, { graph: buildGraph() });
    const g2 = buildGraph();
    delete g2.graph['src/core/session.js'];
    codeIndex.ingestProject(db, project, { graph: g2 });
    const count = db.prepare("SELECT COUNT(*) c FROM code_symbols WHERE symbol_name = 'startSession'").get().c;
    assert.equal(count, 0);
  });
});

// ─── Search ─────────────────────────────────────────────────────────

describe('code-index search', () => {
  let db;
  const project = path.join(os.tmpdir(), 'ac-codeidx-search-' + Date.now());
  beforeEach(() => { db = createTestDb(); codeIndex.ingestProject(db, project, { graph: buildGraph() }); });
  afterEach(() => { db.close(); });

  it('finds symbols by keyword (FTS5)', () => {
    const results = codeIndex.keywordSymbolSearch(db, 'cosine', { project });
    assert.ok(results.length >= 1);
    assert.equal(results[0].symbol_name, 'cosineSimilarity');
  });

  it('finds symbols by doc content', () => {
    const results = codeIndex.keywordSymbolSearch(db, 'session', { project });
    assert.ok(results.some(r => r.symbol_name === 'startSession'));
  });

  it('hybrid search falls back to keyword when embeddings unavailable', async () => {
    const results = await codeIndex.searchSymbols(db, 'hybrid', { project });
    assert.ok(results.length >= 1);
  });

  it('does not attempt embeddings when disabled (no model load)', async () => {
    let called = 0;
    const orig = embedding.computeEmbedding;
    embedding.computeEmbedding = async () => { called++; return [1, 2, 3]; };
    try {
      await codeIndex.searchSymbols(db, 'hybrid', { project, semantic: true });
    } finally {
      embedding.computeEmbedding = orig;
    }
    assert.equal(called, 0, 'embeddings must stay disabled by default — keyword only');
  });

  it('records access for returned symbols', async () => {
    await codeIndex.searchSymbols(db, 'hybrid', { project });
    await codeIndex.searchSymbols(db, 'hybrid', { project });
    const row = db.prepare("SELECT access_count, last_accessed_at FROM code_symbols WHERE symbol_name = 'hybridSearch'").get();
    assert.ok(row.access_count >= 1, 'retrieval must bump access_count');
    assert.ok(row.last_accessed_at, 'last_accessed_at must be set');
  });
});

// ─── Task-scoped retrieval ─────────────────────────────────────────

describe('code-index task-scoped retrieval', () => {
  let db;
  const project = path.join(os.tmpdir(), 'ac-codeidx-scoped-' + Date.now());
  beforeEach(() => { db = createTestDb(); codeIndex.ingestProject(db, project, { graph: buildGraph() }); });
  afterEach(() => { db.close(); });

  it('returns symbols from task-relevant files with bodies', () => {
    const { symbols, stats } = codeIndex.getTaskScopedSymbols(db, project, 'vector embedding similarity', 2000, { graph: buildGraph() });
    assert.ok(symbols.length >= 1);
    assert.ok(symbols.some(s => s.symbol_name === 'computeEmbedding'));
    assert.ok(symbols.some(s => s.symbol_name === 'cosineSimilarity'));
    assert.ok(symbols.every(s => s.file_path !== 'src/core/session.js'), 'irrelevant file should not dominate');
    assert.ok(stats.estimatedTokens <= 500);
  });

  it('expands into the import closure (search.js imports embedding.js)', () => {
    const { files } = codeIndex.getTaskScopedSymbols(db, project, 'hybrid search', 4000, { graph: buildGraph() });
    assert.ok(files.includes('src/core/search.js'));
    assert.ok(files.includes('src/core/embedding.js'));
  });

  it('caps symbols per file so the budget spreads across files', () => {
    const { symbols } = codeIndex.getTaskScopedSymbols(db, project, 'embedding search session', 4000, { symbolsPerFile: 1, graph: buildGraph() });
    const files = new Set(symbols.map(s => s.file_path));
    assert.ok(files.size >= 2);
  });

  it('respects a tiny token budget', () => {
    const { symbols, stats } = codeIndex.getTaskScopedSymbols(db, project, 'embedding', 200, { graph: buildGraph() });
    assert.ok(stats.estimatedTokens <= 250, 'should stay near budget');
    assert.ok(symbols.length >= 1);
  });
});

// ─── Access tracking + usage-weighted injection ─────────────────────

describe('code-index access tracking', () => {
  let db;
  const project = path.join(os.tmpdir(), 'ac-codeidx-access-' + Date.now());
  beforeEach(() => { db = createTestDb(); codeIndex.ingestProject(db, project, { graph: buildGraph() }); });
  afterEach(() => { db.close(); });

  it('recordSymbolAccess increments counts and dedupes within a batch', () => {
    const n = codeIndex.recordSymbolAccess(db, project, [
      { symbol_name: 'computeEmbedding', file_path: 'src/core/embedding.js', kind: 'function' },
      { symbol_name: 'computeEmbedding', file_path: 'src/core/embedding.js', kind: 'function' }, // duplicate
      { symbol_name: 'hybridSearch', file_path: 'src/core/search.js', kind: 'function' },
    ]);
    assert.equal(n, 2, 'duplicate within one batch counts once');
    const emb = db.prepare("SELECT access_count, last_accessed_at FROM code_symbols WHERE symbol_name = 'computeEmbedding'").get();
    assert.equal(emb.access_count, 1);
    assert.ok(emb.last_accessed_at);
  });

  it('getTaskScopedSymbols records access for injected symbols', () => {
    codeIndex.getTaskScopedSymbols(db, project, 'vector embedding', 2000, { graph: buildGraph() });
    const row = db.prepare("SELECT access_count FROM code_symbols WHERE symbol_name = 'computeEmbedding'").get();
    assert.ok(row.access_count >= 1, 'injected symbols must be marked as used');
  });

  it('prefers more-accessed symbols within a file (usage-weighted)', () => {
    db.prepare("UPDATE code_symbols SET access_count = 50, last_accessed_at = datetime('now') WHERE symbol_name = 'cosineSimilarity'").run();
    db.prepare("UPDATE code_symbols SET access_count = 2 WHERE symbol_name = 'computeEmbedding'").run();
    const { symbols } = codeIndex.getTaskScopedSymbols(db, project, 'embedding', 4000, { graph: buildGraph() });
    const file = symbols.filter(s => s.file_path === 'src/core/embedding.js');
    assert.ok(file.length >= 2);
    assert.equal(file[0].symbol_name, 'cosineSimilarity', 'higher access_count must sort first');
  });

  it('falls back to most-retrieved files when the task matches nothing', () => {
    // Mark search.js as heavily used; query matches no file
    db.prepare("UPDATE code_symbols SET access_count = 99 WHERE symbol_name = 'hybridSearch'").run();
    const { files } = codeIndex.getTaskScopedSymbols(db, project, 'zzz no match zzz', 4000, { graph: buildGraph() });
    assert.ok(files.includes('src/core/search.js'), 'usage-weighted fallback must pick the hot file');
  });

  it('getTopSymbols returns most-retrieved first', () => {
    // Two separate retrieval batches → startSession accumulates 2 uses
    codeIndex.recordSymbolAccess(db, project, [{ symbol_name: 'startSession', file_path: 'src/core/session.js', kind: 'function' }]);
    codeIndex.recordSymbolAccess(db, project, [
      { symbol_name: 'startSession', file_path: 'src/core/session.js', kind: 'function' },
      { symbol_name: 'hybridSearch', file_path: 'src/core/search.js', kind: 'function' },
    ]);
    const top = codeIndex.getTopSymbols(db, project, { limit: 5 });
    assert.equal(top[0].symbol_name, 'startSession');
    assert.equal(top[0].access_count, 2);
    assert.ok(top.every(t => t.access_count > 0));
  });

  it('symbolStats reports access totals', () => {
    codeIndex.recordSymbolAccess(db, project, [{ symbol_name: 'hybridSearch', file_path: 'src/core/search.js', kind: 'function' }]);
    const stats = codeIndex.symbolStats(db, project);
    assert.equal(stats.accesses, 1);
    assert.equal(stats.accessedSymbols, 1);
  });
});

