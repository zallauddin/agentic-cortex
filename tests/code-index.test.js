// Memory safety: NEVER load the real ~400MB embedding model in tests.
// Stub it deterministically and leave embeddings disabled.
const embedding = require('../src/core/embedding');
embedding.computeEmbedding = async function (text) {
  return Array.from({ length: 16 }, (_, i) => ((text || '').length + i) % 7);
};
process.env.AGENTIC_CORTEX_EMBEDDINGS = process.env.AGENTIC_CORTEX_EMBEDDINGS || '0';

/** Create a fresh in-memory DB with the full schema. */
function createTestDb() {
  const db = new Database(':memory:');
  db.pragma('journal_mode = WAL');
  db.pragma('foreign_keys = ON');
  ensureSchema(db);
  return db;
}

/** Build a small synthetic graph (as generated by scripts/generate-graph.mjs). */
function buildGraph() {
  const node = (symbols, extra = {}) => ({
    path: extra.path || 'src/file.js',
    role: 'library',
    exports: symbols.map(s => s.name),
    imports: extra.imports || [],
    symbols,
    ...extra,
  });
  return {
    fingerprint: 'test',
    fileCount: 3,
    apiRoutes: [],
    services: {},
    prismaSchema: { models: [], enums: [] },
    layerMap: { layerCounts: { UI: 0, API: 0, Service: 3, Data: 0 }, crossLayerEdges: {}, requestPath: '', hubFiles: [] },
    paradigms: [],
    techStack: { runtime: ['JavaScript'], frameworks: [], databases: [], tools: [] },
    graph: {
      'src/core/embedding.js': node([
        { name: 'computeEmbedding', kind: 'function', signature: 'async function computeEmbedding(text)', doc: 'Compute a vector embedding for text', body: '{\n  return vec;\n}', startLine: 10 },
        { name: 'cosineSimilarity', kind: 'function', signature: 'function cosineSimilarity(a, b)', doc: 'Cosine similarity between two vectors', body: '{\n  return dot / norm;\n}', startLine: 30 },
      ], { imports: [], exports: ['computeEmbedding', 'cosineSimilarity'] }),
      'src/core/search.js': node([
        { name: 'hybridSearch', kind: 'function', signature: 'function hybridSearch(db, query, vec)', doc: 'Hybrid keyword + semantic search', body: '{\n  return results;\n}', startLine: 5 },
      ], { imports: ['./embedding'], exports: ['hybridSearch'] }),
      'src/core/session.js': node([
        { name: 'startSession', kind: 'function', signature: 'function startSession(db, opts)', doc: 'Start a new memory session', body: '{\n  return sid;\n}', startLine: 5 },
      ], { imports: [], exports: ['startSession'] }),
    },
  };
}

